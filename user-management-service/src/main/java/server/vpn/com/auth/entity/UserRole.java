package server.vpn.com.auth.entity;

/**
 * Перечисление ролей пользователей в системе
 */
public enum UserRole {
    /**
     * Обычный пользователь - может покупать и использовать VPN
     */
    USER,
    
    /**
     * Продавец VPN серверов - может создавать и продавать VPN серверы
     */
    SELLER,
    
    /**
     * Администратор системы - полный доступ
     */
    ADMIN
}